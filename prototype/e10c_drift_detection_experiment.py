"""E10-C.3 synthetic audit of autonomous error-rate change alarms.

Scenarios: stationary baseline, abrupt increase, gradual increase, and a
short noisy-label burst. The evaluator knows change locations only for scoring;
the detector receives the sequential binary error stream only.
"""
from __future__ import annotations

import argparse
import json
import random
import statistics
from typing import Any

from prototype.e10c_drift_detector import BernoulliCUSUM


def _bernoulli_stream(rng: random.Random, rates: list[float]) -> list[bool]:
    return [rng.random() < rate for rate in rates]


def _scenario(seed: int, kind: str, length: int = 300) -> tuple[list[bool], int | None]:
    rng = random.Random(seed)
    if kind == "stationary":
        return _bernoulli_stream(rng, [0.05] * length), None
    if kind == "abrupt":
        change = 120
        return _bernoulli_stream(rng, [0.05] * change + [0.55] * (length-change)), change
    if kind == "gradual":
        change = 100
        rates = [0.05] * change + [
            0.05 + 0.50 * (i + 1) / 80 for i in range(80)
        ] + [0.55] * (length-change-80)
        return _bernoulli_stream(rng, rates), change
    if kind == "noise_burst":
        # A transient 12-sample label-noise burst; not a persistent mechanism change.
        start = 120
        rates = [0.05] * start + [0.30] * 12 + [0.05] * (length-start-12)
        return _bernoulli_stream(rng, rates), None
    raise ValueError(f"unknown scenario: {kind}")


def run(*, seeds: int = 30, start_seed: int = 3100,
        threshold: float = 8.0) -> dict[str, Any]:
    if seeds < 1:
        raise ValueError("seeds must be >= 1")
    summaries: dict[str, Any] = {}
    for kind in ("stationary", "abrupt", "gradual", "noise_burst"):
        rows = []
        for seed in range(start_seed, start_seed + seeds):
            errors, change = _scenario(seed, kind)
            detector = BernoulliCUSUM(threshold=threshold)
            alarms = detector.run(errors)
            first = alarms[0].index if alarms else None
            post_change = (
                [alarm.index for alarm in alarms if change is not None and alarm.index > change]
            )
            delay = post_change[0] - change if post_change else None
            rows.append({
                "seed": seed,
                "change_index": change,
                "first_alarm_index": first,
                "alarm_count": len(alarms),
                "post_change_detection_delay": delay,
            })
        detected = [r["post_change_detection_delay"] for r in rows
                    if r["post_change_detection_delay"] is not None]
        summaries[kind] = {
            "runs": rows,
            "alarm_run_rate": sum(r["alarm_count"] > 0 for r in rows) / seeds,
            "mean_alarm_count": statistics.mean(r["alarm_count"] for r in rows),
            "detection_rate": (len(detected) / seeds) if kind in {"abrupt", "gradual"} else None,
            "mean_detection_delay": statistics.mean(detected) if detected else None,
            "median_detection_delay": statistics.median(detected) if detected else None,
        }
    return {
        "experiment": "E10-C.3 Bernoulli CUSUM drift alarm audit",
        "configuration": {
            "seeds": seeds, "start_seed": start_seed, "stream_length": 300,
            "baseline_error_rate": 0.05, "alternative_error_rate": 0.40,
            "threshold": threshold, "detector_input": "binary prequential error only",
        },
        "scenarios": summaries,
        "checks": {
            "stationary_false_alarm_rate_reported": True,
            "abrupt_detection_rate_reported": True,
            "gradual_detection_rate_reported": True,
            "transient_noise_burst_alarm_rate_reported": True,
        },
        "limitations": [
            "Synthetic Bernoulli streams are not generated by the E10 relational learner.",
            "The detector assumes a fixed baseline and design alternative; calibration under real task distributions is untested.",
            "An alarm indicates a change in observed error rate, not proof of concept drift or its cause.",
            "The detector does not segment epochs, adjudicate labels, expand hypotheses, or modify learner state.",
            "The transient burst is a finite noisy-label stress case, not a comprehensive noise model.",
        ],
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--seeds", type=int, default=30)
    parser.add_argument("--start-seed", type=int, default=3100)
    parser.add_argument("--threshold", type=float, default=8.0)
    args = parser.parse_args()
    print(json.dumps(run(seeds=args.seeds, start_seed=args.start_seed,
                         threshold=args.threshold), indent=2, ensure_ascii=False))
