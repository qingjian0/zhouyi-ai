"""E03-A: parallel multi-relation discovery with global feature-budget coordination.

Three output channels are generated by distinct hidden Boolean hyperedges.
Each channel proposes candidates in parallel. A global coordinator selects a
joint candidate set under a shared feature budget, then a locked test audits it.
This is a finite synthetic architecture experiment, not a general AI claim.
"""
from __future__ import annotations

import argparse
import itertools
import json
import random
from dataclasses import asdict

from prototype.e02h_boolean_rules import (
    Candidate, accuracy, admissible_target_tables, make_rows, _rank_subset,
)


TARGET_TRIPLES = ((0, 2, 5), (2, 5, 7), (0, 4, 7))
FEATURE_BUDGET = 5
SHORTLIST = 8


def _candidate_pool(train, *, adjacent_only: bool = False) -> list[Candidate]:
    width = len(train[0].values)
    subsets = []
    for order in (2, 3):
        for members in itertools.combinations(range(width), order):
            if adjacent_only and members != tuple(range(members[0], members[0] + order)):
                continue
            subsets.append(_rank_subset(train, members))
    return sorted(subsets, key=lambda c: (-c.train_accuracy, len(c.members),
                                          c.members, c.truth_table))


def _signature(c: Candidate) -> tuple:
    return c.members, c.truth_table


def _select_global(shortlists: list[list[Candidate]], gates: list[list],
                   budget: int = FEATURE_BUDGET) -> tuple[Candidate, ...]:
    best = None
    best_score = float("-inf")
    for combo in itertools.product(*shortlists):
        union = set().union(*(set(c.members) for c in combo))
        if len(union) > budget:
            continue
        # A relation cannot be assigned twice to different output channels.
        if len({_signature(c) for c in combo}) != len(combo):
            continue
        score = sum(accuracy(gate, candidate)
                    for gate, candidate in zip(gates, combo))
        tie = tuple((_signature(c)) for c in combo)
        if score > best_score or (score == best_score and
                                  (best is None or tie < tuple(_signature(c) for c in best))):
            best, best_score = combo, score
    if best is None:
        raise RuntimeError("global coordinator found no budget-feasible candidate set")
    return best


def _audit(selected: tuple[Candidate, ...], targets: tuple[tuple[int, ...], ...],
           tables: tuple[int, ...], tests: list[list]) -> dict:
    exact_members = []
    exact_rules = []
    test_scores = []
    for candidate, target, table, test in zip(selected, targets, tables, tests):
        exact_members.append(set(candidate.members) == set(target))
        exact_rules.append(candidate.members == target and candidate.truth_table == table)
        test_scores.append(accuracy(test, candidate))
    return {
        "member_recovery": sum(exact_members) / len(exact_members),
        "exact_rule_recovery": sum(exact_rules) / len(exact_rules),
        "mean_test_accuracy": sum(test_scores) / len(test_scores),
        "per_head_test_accuracy": test_scores,
        "per_head_members": [list(c.members) for c in selected],
        "union_feature_count": len(set().union(*(set(c.members) for c in selected))),
    }


def run_episode(seed: int, *, train_n: int = 1024, gate_n: int = 512,
                test_n: int = 512, noise: float = 0.02) -> dict:
    rng = random.Random(seed * 313 + 17)
    tables = tuple(rng.sample(admissible_target_tables(), 3))
    targets = TARGET_TRIPLES

    trains, gates, tests = [], [], []
    pools, adjacent_pools = [], []
    for head, (members, table) in enumerate(zip(targets, tables)):
        # Identical feature vectors across heads make shared-feature coordination
        # meaningful; head labels differ by target relation.
        base = seed * 100000
        trains.append(make_rows(seed=base + 1, count=train_n,
                                target_members=members, target_table=table, noise=noise))
        gates.append(make_rows(seed=base + 2, count=gate_n,
                               target_members=members, target_table=table, noise=noise))
        tests.append(make_rows(seed=base + 3, count=test_n,
                               target_members=members, target_table=table, noise=noise))
        pools.append(_candidate_pool(trains[-1]))
        adjacent_pools.append(_candidate_pool(trains[-1], adjacent_only=True))

    shortlists = [pool[:SHORTLIST] for pool in pools]
    coordinated = _select_global(shortlists, gates)

    # Ablation: choose each head's best gate candidate independently, with no
    # global feature-budget constraint.
    independent = tuple(max(shortlist, key=lambda c: (accuracy(gate, c),
                                                       c.train_accuracy,
                                                       tuple(-x for x in c.members)))
                        for shortlist, gate in zip(shortlists, gates))
    # Fair ablation: restrict the candidate language to adjacent subsets,
    # but use the same independent gate-selection protocol as the baseline.
    adjacent = tuple(max(pool, key=lambda c: (accuracy(gate, c),
                                               c.train_accuracy,
                                               tuple(-x for x in c.members)))
                     for pool, gate in zip(adjacent_pools, gates))

    coord_audit = _audit(coordinated, targets, tables, tests)
    independent_audit = _audit(independent, targets, tables, tests)
    adjacent_audit = _audit(adjacent, targets, tables, tests)

    return {
        "seed": seed,
        "target_members_for_audit_only": [list(x) for x in targets],
        "target_tables_for_audit_only": list(tables),
        "candidate_counts_per_head": [len(pool) for pool in pools],
        "shortlist_size": SHORTLIST,
        "feature_budget": FEATURE_BUDGET,
        "coordinated": coord_audit,
        "independent_gate_selection": independent_audit,
        "adjacent_only_ablation": adjacent_audit,
        "independent_within_budget": independent_audit["union_feature_count"] <= FEATURE_BUDGET,
    }


def run(seeds: int = 30, start_seed: int = 1500) -> dict:
    episodes = [run_episode(start_seed + i) for i in range(seeds)]
    def mean(path):
        vals = []
        for episode in episodes:
            value = episode
            for key in path:
                value = value[key]
            vals.append(value)
        return sum(vals) / len(vals)
    return {
        "task": "E03A_parallel_multirelation_global_coordination",
        "seeds": seeds,
        "settings": {
            "width": 8, "heads": 3, "candidate_orders": "2..3",
            "candidate_subsets_per_head": 84,
            "shortlist_per_head": SHORTLIST,
            "global_joint_combinations_max": SHORTLIST ** 3,
            "shared_feature_budget": FEATURE_BUDGET,
            "target_triples": [list(x) for x in TARGET_TRIPLES],
            "train_gate_test": [1024, 512, 512],
            "noise": 0.02,
        },
        "summary": {
            "coordinated_member_recovery": mean(["coordinated", "member_recovery"]),
            "coordinated_exact_rule_recovery": mean(["coordinated", "exact_rule_recovery"]),
            "coordinated_test_accuracy": mean(["coordinated", "mean_test_accuracy"]),
            "independent_member_recovery": mean(["independent_gate_selection", "member_recovery"]),
            "independent_exact_rule_recovery": mean(["independent_gate_selection", "exact_rule_recovery"]),
            "independent_test_accuracy": mean(["independent_gate_selection", "mean_test_accuracy"]),
            "independent_within_budget_rate": sum(e["independent_within_budget"] for e in episodes) / seeds,
            "adjacent_only_member_recovery": mean(["adjacent_only_ablation", "member_recovery"]),
            "adjacent_only_test_accuracy": mean(["adjacent_only_ablation", "mean_test_accuracy"]),
            "mean_coordinated_union_features": mean(["coordinated", "union_feature_count"]),
        },
        "episodes": episodes,
        "limitations": [
            "Synthetic multi-output binary Boolean tasks only.",
            "The three target triples are fixed in advance and contain non-adjacent members.",
            "Candidate language is exhaustive over 2- and 3-feature truth tables; it is not open-ended.",
            "The global coordinator optimizes gate accuracy under a fixed feature budget; its objective is hand-designed.",
            "This does not test language, causal discovery, continuous state, learned coordination policy, or real-world generalization.",
        ],
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seeds", type=int, default=30)
    parser.add_argument("--start-seed", type=int, default=1500)
    args = parser.parse_args()
    print(json.dumps(run(args.seeds, args.start_seed), indent=2))


if __name__ == "__main__":
    main()
